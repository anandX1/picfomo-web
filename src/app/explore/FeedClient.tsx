"use client";

import { useState, useTransition, useEffect, useRef, useCallback } from "react";
import { Heart, Zap, Loader2, X, Eye, User, Search, TrendingUp, Clock, Sparkles } from "lucide-react";
import { likePost, mockRemixPost } from "@/actions/economy";
import { fetchFeedChunk } from "@/actions/feed"; 
import Link from "next/link"; 
import { toast } from "sonner"; 
import { useRouter } from "next/navigation"; 
import Script from "next/script";
import Image from "next/image";

interface Post {
  id: string;
  image_url: string;
  user_id: string;
  created_at: string;
  style_name: string | null;
  likes_count: number;
  views_count: number;
  remix_count: number;
  is_liked_by_me: number; 
  username: string | null;
  profile_image_url: string | null;
  is_wildcard?: number; 
}

interface Props {
  initialPosts: Post[];
  currentUserId: string | null; 
  initialRemixData?: any; 
}

type FeedTab = "trending" | "latest" | "portraits" | "art";
const TABS: { id: FeedTab; label: string; icon: React.ReactNode }[] = [
  { id: "trending",  label: "Trending",    icon: <TrendingUp size={13} /> },
  { id: "latest",    label: "Latest",      icon: <Clock size={13} /> },
  { id: "portraits", label: "Portraits",   icon: <User size={13} /> },
  { id: "art",       label: "Art & Style", icon: <Sparkles size={13} /> },
];

function PostSkeleton() {
  return (
    <div className="break-inside-avoid mb-3">
      <div className="rounded-2xl bg-gray-100 animate-pulse mb-2 aspect-[4/5] w-full" />
      <div className="flex items-center gap-2 px-1 mb-6">
        <div className="h-6 w-6 rounded-full bg-gray-200 animate-pulse shrink-0" />
        <div className="h-3 w-24 rounded-full bg-gray-200 animate-pulse" />
      </div>
    </div>
  );
}

function PostCard({
  post, index, currentUserId, isPending, animatedPostId,
  onLike, onRemix, onDoubleTap, refProp,
}: {
  post: Post; index: number; currentUserId: string | null; isPending: boolean;
  animatedPostId: string | null;
  onLike: (id: string, e: React.MouseEvent) => void;
  onRemix: (id: string, e?: React.MouseEvent) => void;
  onDoubleTap: (id: string, e: React.MouseEvent) => void;
  refProp?: (node: HTMLDivElement) => void;
}) {
  const isMine = post.user_id === currentUserId;
  const isLiked = post.is_liked_by_me > 0;
  const displayUsername = post.username || `user_${post.user_id.substring(0, 6)}`;
  const showAd = (index + 1) % 5 === 0;

  return (
    <div className="break-inside-avoid group">
      <div
        ref={refProp}
        className="relative rounded-2xl overflow-hidden bg-gray-100 mb-2 cursor-pointer select-none"
        onDoubleClick={(e) => onDoubleTap(post.id, e)}
      >
        {post.is_wildcard === 1 && (
          <div className="absolute top-2 left-2 z-20 bg-black/60 backdrop-blur-md text-white text-[10px] font-bold px-2 py-1 rounded-full flex items-center gap-1 border border-white/20 shadow-lg pointer-events-none">
            <Sparkles size={10} className="text-yellow-400" /> NEW
          </div>
        )}

        {/* 🌟 FIX 1: Locked strictly to aspect-[4/5] to permanently stop CLS jumping and the infinite observer loop! */}
        <Link href={`/post/${post.id}`} className="block relative z-0 w-full aspect-[4/5]">
          <Image
            src={post.image_url}
            alt={`Generated by ${displayUsername}`}
            fill
            priority={index < 4}
            sizes="(max-width: 640px) 50vw, (max-width: 1024px) 33vw, 20vw"
            className="object-cover transition-all duration-500 group-hover:scale-[1.02] group-hover:brightness-95"
            unoptimized
          />
        </Link>

        {animatedPostId === post.id && (
          <div className="absolute inset-0 flex items-center justify-center pointer-events-none z-10">
            <Heart size={80} className="fill-white text-white drop-shadow-2xl animate-out fade-out zoom-out duration-700" />
          </div>
        )}

        <div className="hidden md:flex absolute inset-0 bg-black/20 opacity-0 group-hover:opacity-100 transition-opacity duration-300 pointer-events-none flex-col justify-between p-3 z-10">
          <div className="flex justify-end">
            <button onClick={(e) => onRemix(post.id, e)} disabled={isPending || isMine} className="bg-[var(--color-gold)] text-[var(--color-ink)] rounded-full px-4 py-2.5 font-bold text-xs shadow-lg pointer-events-auto hover:scale-105 active:scale-95 transition-transform flex items-center gap-1.5 disabled:opacity-50">
              <Zap size={14} className="fill-[var(--color-ink)]" /> {isMine ? "YOURS" : "REMIX"}
            </button>
          </div>
          <div className="flex justify-end">
            <button onClick={(e) => onLike(post.id, e)} disabled={isPending || isMine} className="bg-white/90 backdrop-blur-sm text-gray-900 rounded-full p-2.5 shadow-lg pointer-events-auto hover:bg-white hover:scale-105 transition-all disabled:opacity-50">
              <Heart size={18} className={isLiked ? "fill-red-500 text-red-500" : ""} />
            </button>
          </div>
        </div>
      </div>

      <div className="flex items-center justify-between px-1 mb-6">
        <Link href={`/u/${displayUsername}`} className="flex items-center gap-2 hover:opacity-80 transition-opacity">
          <div className="h-6 w-6 shrink-0 overflow-hidden rounded-full bg-gray-200 flex items-center justify-center relative">
            {post.profile_image_url
              ? <Image src={post.profile_image_url} alt={displayUsername} fill className="object-cover" unoptimized />
              : <User size={14} className="text-gray-400" />}
          </div>
          <span className="truncate font-semibold text-xs text-gray-900">{displayUsername}</span>
        </Link>
        <div className="flex items-center gap-3 text-gray-500">
          <div className="flex md:hidden items-center gap-1">
            <Heart size={12} className={isLiked ? "fill-red-500 text-red-500" : ""} />
            <span className="text-[10px] font-bold">{post.likes_count}</span>
          </div>
          <div className="flex items-center gap-1">
            <Eye size={14} />
            <span className="text-[11px] font-bold">{post.views_count}</span>
          </div>
        </div>
      </div>

      {showAd && (
        <div className="mb-6 w-full rounded-2xl border border-gray-200 bg-gray-50 flex flex-col items-center justify-center overflow-hidden relative min-h-[250px] p-2">
          <span className="text-[9px] text-gray-400 uppercase tracking-widest font-bold absolute top-2 left-3 z-10">Sponsored</span>
          <div id="container-b39280394b30c04b29a8908fb4b0bd64" className="mt-4 w-full flex justify-center"></div>
          <Script id={`adsterra-native-${index}`} src="https://pl29173183.profitablecpmratenetwork.com/b39280394b30c04b29a8908fb4b0bd64/invoke.js" strategy="afterInteractive" data-cfasync="false" async />
        </div>
      )}
    </div>
  );
}

export default function FeedClient({ initialPosts, currentUserId, initialRemixData }: Props) {
  const router = useRouter();
  const [isPending, startTransition] = useTransition();
  const [showAuthModal, setShowAuthModal] = useState(false);
  const [posts, setPosts] = useState<Post[]>(initialPosts);
  const [animatedPostId, setAnimatedPostId] = useState<string | null>(null);
  const [showCollabModal, setShowCollabModal] = useState(!!initialRemixData);

  const [activeTab, setActiveTab] = useState<FeedTab>("trending");
  const [isTabLoading, setIsTabLoading] = useState(false);
  const [searchQuery, setSearchQuery] = useState("");
  const [isSearching, setIsSearching] = useState(false);

  const [offset, setOffset] = useState(15);
  const [hasMore, setHasMore] = useState(initialPosts.length === 15);
  const [isLoadingMore, setIsLoadingMore] = useState(false);
  const observerRef = useRef<IntersectionObserver | null>(null);

  const handleTabChange = async (tab: FeedTab) => {
    if (tab === activeTab) return;
    setActiveTab(tab);
    setIsTabLoading(true);
    setSearchQuery("");
    const results = await fetchFeedChunk(0, 15, "", tab);
    setPosts(results);
    setOffset(15);
    setHasMore(results.length === 15);
    setIsTabLoading(false);
  };

  const handleSearch = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsSearching(true);
    const results = await fetchFeedChunk(0, 15, searchQuery);
    setPosts(results);
    setOffset(15);
    setHasMore(results.length === 15);
    setIsSearching(false);
  };

  // 🌟 FIX 2: Throttled intersection observer to prevent rapid-fire DB calls
  const lastPostElementRef = useCallback((node: HTMLDivElement) => {
    if (isLoadingMore || isSearching) return;
    if (observerRef.current) observerRef.current.disconnect();
    observerRef.current = new IntersectionObserver(entries => {
      if (entries[0].isIntersecting && hasMore) {
        loadMorePosts();
      }
    }, { rootMargin: '400px' });
    if (node) observerRef.current.observe(node);
  }, [isLoadingMore, hasMore, isSearching]);

  const loadMorePosts = async () => {
    setIsLoadingMore(true);
    const newPosts = await fetchFeedChunk(offset, 15, searchQuery, activeTab);
    if (newPosts.length === 0) {
      setHasMore(false);
    } else {
      setPosts(prev => {
        // Prevent duplicate appending
        const newIds = new Set(newPosts.map(p => p.id));
        const filteredPrev = prev.filter(p => !newIds.has(p.id));
        return [...filteredPrev, ...newPosts];
      });
      setOffset(prev => prev + 15);
      if (newPosts.length < 15) setHasMore(false);
    }
    setIsLoadingMore(false);
  };

  useEffect(() => {
    if (!currentUserId && !initialRemixData) {
      const timer = setTimeout(() => setShowAuthModal(true), 20000);
      return () => clearTimeout(timer);
    }
  }, [currentUserId, initialRemixData]);

  const triggerHeartAnimation = (postId: string) => {
    setAnimatedPostId(postId);
    setTimeout(() => setAnimatedPostId(null), 800);
  };

  const handleLike = (postId: string, e: React.MouseEvent) => {
    e.preventDefault(); e.stopPropagation();
    if (!currentUserId) return setShowAuthModal(true);
    const targetPost = posts.find(p => p.id === postId);
    if (!targetPost) return;
    if (targetPost.is_liked_by_me > 0) { triggerHeartAnimation(postId); return; }
    triggerHeartAnimation(postId);
    setPosts(prev => prev.map(p => p.id === postId ? { ...p, likes_count: p.likes_count + 1, is_liked_by_me: 1 } : p));
    startTransition(async () => {
      const res = await likePost(postId);
      if (res.success) toast.success("Liked! Creator earned +1 ⚡");
      else {
        setPosts(prev => prev.map(p => p.id === postId ? { ...p, likes_count: p.likes_count - 1, is_liked_by_me: 0 } : p));
        toast.error(res.message);
      }
    });
  };

  const handleRemix = (postId: string, e?: React.MouseEvent) => {
    if (e) { e.preventDefault(); e.stopPropagation(); }
    if (!currentUserId) return setShowAuthModal(true);
    startTransition(async () => {
      const res = await mockRemixPost(postId);
      if (res.success) { toast.success("Collab Successful! View it in your Vault."); setShowCollabModal(false); router.replace('/explore'); }
      else toast.error(res.message);
    });
  };

  const handleDoubleTap = (postId: string, e: React.MouseEvent) => {
    e.preventDefault(); e.stopPropagation();
    handleLike(postId, e);
  };

  const closeCollabModal = () => { setShowCollabModal(false); router.replace('/explore'); };
  const isLoading = isSearching || isTabLoading;

  return (
    <div className="mx-auto max-w-[1600px] p-4 md:p-8 relative min-h-screen">

      {/* COLLAB MODAL */}
      {showCollabModal && initialRemixData && (
        <div className="fixed inset-0 z-[60] flex items-center justify-center bg-black/80 backdrop-blur-md px-4 animate-in fade-in duration-300">
          <div className="relative w-full max-w-sm overflow-hidden rounded-[24px] bg-white p-6 shadow-2xl flex flex-col items-center">
            <button onClick={closeCollabModal} className="absolute right-4 top-4 z-10 rounded-full bg-black/10 p-2 text-gray-800 transition-colors hover:bg-black/20"><X size={16} /></button>
            <h2 className="font-extrabold text-2xl text-center mb-1">Collab Request 🤝</h2>
            <p className="text-gray-500 text-sm text-center mb-6">Remixing style from <span className="font-bold text-gray-900">@{initialRemixData.username || "creator"}</span></p>
            <div className="relative w-full aspect-[4/5] rounded-xl overflow-hidden mb-6 shadow-md border border-gray-200 bg-gray-100">
              <Image src={initialRemixData.image_url} alt="Remix Target" fill sizes="(max-width: 768px) 100vw, 400px" className="object-cover" unoptimized />
            </div>
            <button onClick={() => handleRemix(initialRemixData.id)} disabled={isPending} className="w-full bg-gradient-to-r from-yellow-400 to-orange-500 text-white font-extrabold py-4 rounded-xl shadow-lg hover:scale-105 active:scale-95 transition-all disabled:opacity-50 flex justify-center items-center gap-2">
              {isPending ? <Loader2 size={18} className="animate-spin" /> : <Zap size={18} className="fill-white" />} Remix Style (-10 Sparks)
            </button>
          </div>
        </div>
      )}

      {/* AUTH MODAL */}
      {showAuthModal && !currentUserId && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-md px-4 animate-in fade-in duration-300">
          <div className="relative w-full max-w-md overflow-hidden rounded-[24px] bg-[var(--color-white)] p-8 shadow-2xl border border-white/20">
            <div className="absolute -top-24 -left-24 h-48 w-48 rounded-full bg-blue-400 opacity-10 blur-3xl animate-pulse"></div>
            <div className="absolute -bottom-24 -right-24 h-48 w-48 rounded-full bg-[var(--color-gold)] opacity-10 blur-3xl animate-pulse" style={{ animationDelay: '1s' }}></div>
            <button onClick={() => setShowAuthModal(false)} className="absolute right-4 top-4 z-10 rounded-full bg-gray-50 p-2 text-gray-500 hover:bg-gray-200"><X size={16} /></button>
            <div className="relative z-10 flex flex-col items-center text-center">
              <Image src="/logo.png" alt="PicFOMO Logo" width={192} height={48} className="mb-6 w-40 sm:w-48 h-auto rounded-xl shadow-lg object-contain" unoptimized />
              <h2 className="mb-2 font-[family-name:var(--display)] text-3xl text-[var(--color-ink)] tracking-tight">Unlock Your Aesthetic</h2>
              <p className="mb-8 font-[family-name:var(--mono)] text-[12px] uppercase leading-relaxed tracking-[1px] text-[var(--color-ink3)]">Drop your photo. Pick a trending style.<br/> Get your portrait in ~20 seconds.</p>
              <Link href="/sign-up" className="group relative flex w-full items-center justify-center overflow-hidden rounded-full bg-gray-900 py-4 font-bold tracking-wide text-white hover:scale-[1.02] active:scale-[0.98] shadow-lg">
                <span className="relative z-10">Create Free Account</span>
              </Link>
            </div>
          </div>
        </div>
      )}

      {/* HEADER & SEARCH */}
      <div className="mb-6 flex flex-col md:flex-row md:items-end md:justify-between gap-6">
        <div>
          <h1 className="mb-2 font-[family-name:var(--display)] text-4xl tracking-[-0.5px] text-[var(--color-ink)]">DISCOVER</h1>
          <p className="font-[family-name:var(--mono)] text-[12px] uppercase tracking-[2px] text-[var(--color-ink3)]">Trending styles tailored to your taste</p>
        </div>
        <form onSubmit={handleSearch} className="w-full md:w-96 relative">
          <input type="text" placeholder="Search tags, creators, or prompts..." value={searchQuery} onChange={(e) => setSearchQuery(e.target.value)} className="w-full bg-white border border-gray-200 rounded-full py-3.5 pl-12 pr-4 text-sm font-medium focus:outline-none focus:ring-2 focus:ring-black shadow-sm" />
          <Search size={18} className="absolute left-5 top-4 text-gray-400" />
          <button type="submit" disabled={isSearching} className="hidden">Search</button>
        </form>
      </div>

      {/* TABS */}
      <div className="flex gap-2 mb-8 overflow-x-auto pb-1 scrollbar-hide">
        {TABS.map((tab) => (
          <button key={tab.id} onClick={() => handleTabChange(tab.id)} disabled={isTabLoading}
            className={`flex items-center gap-1.5 px-4 py-2 rounded-full text-sm font-bold whitespace-nowrap transition-all ${
              activeTab === tab.id ? 'bg-gray-900 text-white shadow-md' : 'bg-white text-gray-600 border border-gray-200 hover:border-gray-400'
            }`}
          >
            {tab.icon}{tab.label}
          </button>
        ))}
      </div>

      {/* GRID */}
      {isLoading ? (
        <div className="columns-2 gap-3 sm:columns-3 lg:columns-4 xl:columns-5 md:gap-4 pb-20">
          {Array.from({ length: 10 }).map((_, i) => <PostSkeleton key={i} />)}
        </div>
      ) : posts.length === 0 ? (
        <div className="flex flex-col items-center justify-center py-20 text-center">
          <span className="mb-4 text-6xl">🔍</span>
          <h3 className="font-[family-name:var(--display)] text-2xl text-[var(--color-ink)]">NO POSTS FOUND</h3>
        </div>
      ) : (
        <div className="columns-2 gap-3 sm:columns-3 lg:columns-4 xl:columns-5 md:gap-4 pb-20">
          {posts.map((post, index) => (
            <PostCard
              key={`${post.id}-${index}`}
              post={post} index={index}
              currentUserId={currentUserId}
              isPending={isPending}
              animatedPostId={animatedPostId}
              onLike={handleLike} onRemix={handleRemix} onDoubleTap={handleDoubleTap}
              refProp={index === posts.length - 3 ? lastPostElementRef : undefined}
            />
          ))}
        </div>
      )}

      {isLoadingMore && (
        <div className="w-full flex justify-center py-6 pb-20">
          <Loader2 size={24} className="animate-spin text-gray-400" />
        </div>
      )}
    </div>
  );
}